export function getWukuByNomor(nomor: number): WukuDetailInfo {
  const index = Math.max(1, Math.min(30, nomor)) - 1;
  return DAFTAR_30_WUKU[index];
}

export function getWukuByName(nama: string): WukuDetailInfo {
  const cleaned = nama.trim().toLowerCase();
  const found = DAFTAR_30_WUKU.find((w) => w.nama.toLowerCase() === cleaned);
  return found || DAFTAR_30_WUKU[0];
}
